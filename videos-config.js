/**
 * Универсальная функция получения ссылки на видео.
 * Поддерживает:
 * - Прямые внешние ссылки (http:// или https://)
 * - Персональные соответствия из VIDEO_MAP
 * - Подстановку VIDEO_CDN_BASE
 * - Локальный резервный путь (fallback)
 */
function getVideoUrl(filename) {
    if (!filename || typeof filename !== "string") return "";

    // 1. Если передан уже готовый полный URL
    if (filename.startsWith("http://") || filename.startsWith("https://") || filename.startsWith("//")) {
        return filename;
    }

    // Извлекаем только имя файла, если передан относительный путь
    const cleanName = filename.split("/").pop().split("\\").pop();

    // 2. Проверяем точечный маппинг в VIDEO_MAP
    if (VIDEO_MAP[cleanName] && VIDEO_MAP[cleanName].trim() !== "") {
        return VIDEO_MAP[cleanName].trim();
    }

    // 3. Проверяем общий CDN Base URL
    if (VIDEO_CDN_BASE && VIDEO_CDN_BASE.trim() !== "") {
        const base = VIDEO_CDN_BASE.trim().endsWith("/") ? VIDEO_CDN_BASE.trim() : VIDEO_CDN_BASE.trim() + "/";
        return base + cleanName;
    }

    // 4. Резервный локальный путь
    return filename;
}

